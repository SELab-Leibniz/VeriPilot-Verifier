import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { loadConfig } from '../lib/runtime-corrector.mjs';
import { loadProjectPolicySource } from '../lib/policy/project-policy.mjs';

test('new project template loads the supplied Stop and requirement-frame profile behind the session control', async t => {
  const projectRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'rc-original-basis-'));
  t.after(() => fs.rm(projectRoot, { recursive: true, force: true }));
  await fs.cp(new URL('../.runtime-corrector-default/', import.meta.url), path.join(projectRoot, '.runtime-corrector'), { recursive: true });
  const plan = await loadConfig({ cwd: projectRoot });
  const { runtimeV2: runtime } = plan;
  const controls = await loadProjectPolicySource(projectRoot);
  assert.equal(controls.enabled, true);
  assert.equal(controls.sessionDefaults.enabled, false);
  assert.deepEqual(runtime.artifactCorrection, { originalRequirementsEnabled: false, groundTruthReviewEnabled: false, stageMetricsEnabled: false });
  assert.equal(runtime.stopCorrection.enabled, true);
  assert.equal(runtime.stopCorrection.originalRequirementsBasis, true);
  assert.equal(Boolean(runtime.stopCorrection.deviationOnly), false);
  assert.equal(runtime.stopCorrection.waitMode, 'until_pass');
  assert.equal(runtime.stopCorrection.assessmentTimeoutMs, 7_200_000);
  assert.equal(runtime.stopCorrection.feedbackReserveMs, 300_000);
  assert.equal(runtime.stopCorrection.maxCorrectionsPerSession, 3);
  assert.equal(runtime.stopCorrection.maxCorrectionsPerFlow, 3);
  assert.equal(runtime.stopCorrection.regressionCheck.enabled, false);
  assert.deepEqual(runtime.stopCorrection.regressionCheck.command, controls.stopCorrection.regressionCheck.command);
  assert.equal(runtime.stopCorrection.regressionCheck.timeoutMs, 1_800_000);
  assert.deepEqual(runtime.stopCorrection.metrics, Object.fromEntries(Array.from({ length: 16 }, (_, index) => {
    const id = `M${String(index + 1).padStart(2, '0')}`;
    return [id, id !== 'M08' && id !== 'M12'];
  })));
  assert.equal(runtime.requirementFrame.enabled, true);
  assert.equal(runtime.requirementFrame.checks, true);
  assert.equal(runtime.dynamicGroundTruth.enabled, false);
  assert.equal(runtime.skillCorrection.enabled, false);
  assert.equal(runtime.implementationCorrection.enabled, false);
  assert.notEqual(runtime.compactionRestore?.enabled, true);
  assert.equal(controls.reviewers.defaults.model, 'custom/deepseek-v4.1-flash');
  assert.equal(controls.reviewers.stopReviewer.model, 'custom/deepseek-v4.1-flash');
  assert.deepEqual(plan.enabledStages, []);
  assert.deepEqual(plan.artifacts, []);
  assert.deepEqual(plan.reviewGraph.edges.map(({from,to})=>[from,to]), [['proposal','design'],['proposal','tasks'],['design','tasks']]);
  assert.deepEqual(plan.configuredArtifacts.map(item => item.nodeId), ['proposal', 'design', 'tasks']);
});
